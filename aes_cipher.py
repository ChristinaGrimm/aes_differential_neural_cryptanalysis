RCON = np.array([0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36], dtype=np.uint8)

_galois_lookup = np.zeros((256, 256), dtype=np.uint8)
for _a in range(256):
    for _b in range(256):
        p = 0
        x, y = _a, _b
        for _ in range(8):
            if y & 1:
                p ^= x
            hi = x & 0x80
            x = (x << 1) & 0xff
            if hi:
                x ^= 0x1b
            y >>= 1
        _galois_lookup[_a, _b] = p


def _galois_mat_mult(mat, state):
    n = state.shape[0]
    out = np.zeros_like(state, dtype=np.uint8)
    for i in range(4):
        for k in range(4):
            out[:, i, :] ^= _galois_lookup[mat[i, k], state[:, k, :]]
    return out


_MIX_MAT = np.array([[2, 3, 1, 1],
                      [1, 2, 3, 1],
                      [1, 1, 2, 3],
                      [3, 1, 1, 2]], dtype=np.uint8)

_INV_MIX_MAT = np.array([[14, 11, 13,  9],
                          [ 9, 14, 11, 13],
                          [13,  9, 14, 11],
                          [11, 13,  9, 14]], dtype=np.uint8)




def _sub_bytes(state):
    return SBOX[state]


def _inv_sub_bytes(state):
    return INV_SBOX[state]


def _shift_rows(state):
    s = state.copy()
    s[:, 1, :] = state[:, 1, [1, 2, 3, 0]]
    s[:, 2, :] = state[:, 2, [2, 3, 0, 1]]
    s[:, 3, :] = state[:, 3, [3, 0, 1, 2]]
    return s


def _inv_shift_rows(state):
    s = state.copy()
    s[:, 1, :] = state[:, 1, [3, 0, 1, 2]]
    s[:, 2, :] = state[:, 2, [2, 3, 0, 1]]
    s[:, 3, :] = state[:, 3, [1, 2, 3, 0]]
    return s


def _mix_columns(state):
    return _galois_mat_mult(_MIX_MAT, state)


def _inv_mix_columns(state):
    return _galois_mat_mult(_INV_MIX_MAT, state)


def _add_round_key(state, rk):
    return state ^ rk



def expand_key(keys, nr):
    n = keys.shape[0]
    key = keys.reshape(n, 4, 4).transpose(0, 2, 1)
    w = np.zeros((n, 4 * (nr + 1), 4), dtype=np.uint8)
    w[:, :4, :] = key

    for i in range(4, 4 * (nr + 1)):
        temp = w[:, i - 1, :].copy()
        if i % 4 == 0:
            temp = temp[:, [1, 2, 3, 0]]
            temp = SBOX[temp]
            temp[:, 0] ^= RCON[i // 4]
        w[:, i, :] = w[:, i - 4, :] ^ temp

    w = w.reshape(n, nr + 1, 4, 4)
    w = w.transpose(1, 0, 3, 2)
    return w.reshape(nr + 1, n, 16)




def encrypt(pt, round_keys, nr=None, final_mc=False):
    if nr is None:
        nr = round_keys.shape[0] - 1
    n = pt.shape[0]
    state = pt.reshape(n, 4, 4).transpose(0, 2, 1)

    rk0 = round_keys[0].reshape(n, 4, 4).transpose(0, 2, 1)
    state = _add_round_key(state, rk0)

    for i in range(1, nr):
        state = _sub_bytes(state)
        state = _shift_rows(state)
        state = _mix_columns(state)
        rk = round_keys[i].reshape(n, 4, 4).transpose(0, 2, 1)
        state = _add_round_key(state, rk)

    state = _sub_bytes(state)
    state = _shift_rows(state)
    if final_mc:
        state = _mix_columns(state)
    rk_last = round_keys[nr].reshape(n, 4, 4).transpose(0, 2, 1)
    state = _add_round_key(state, rk_last)

    return state.transpose(0, 2, 1).reshape(n, 16)


def decrypt(ct, round_keys, nr=None):
    if nr is None:
        nr = round_keys.shape[0] - 1
    n = ct.shape[0]
    state = ct.reshape(n, 4, 4).transpose(0, 2, 1)

    rk_last = round_keys[nr].reshape(n, 4, 4).transpose(0, 2, 1)
    state = _add_round_key(state, rk_last)
    state = _inv_shift_rows(state)
    state = _inv_sub_bytes(state)

    for i in range(nr - 1, 0, -1):
        rk = round_keys[i].reshape(n, 4, 4).transpose(0, 2, 1)
        state = _add_round_key(state, rk)
        state = _inv_mix_columns(state)
        state = _inv_shift_rows(state)
        state = _inv_sub_bytes(state)

    rk0 = round_keys[0].reshape(n, 4, 4).transpose(0, 2, 1)
    state = _add_round_key(state, rk0)

    return state.transpose(0, 2, 1).reshape(n, 16)




def inv_mix_columns_flat(ct):
    n = ct.shape[0]
    state = ct.reshape(n, 4, 4).transpose(0, 2, 1)
    state = _inv_mix_columns(state)
    return state.transpose(0, 2, 1).reshape(n, 16)


def encrypt_with_invmc(pt, round_keys, nr=None):
    ct_mc = encrypt(pt, round_keys, nr=nr, final_mc=True)
    return inv_mix_columns_flat(ct_mc)



