    from os import urandom

    n_test = 100
    nr_test = 3

    pt = np.frombuffer(urandom(16 * n_test), dtype=np.uint8).reshape(-1, 16)
    keys = np.frombuffer(urandom(16 * n_test), dtype=np.uint8).reshape(-1, 16)
    rk = expand_key(keys, nr_test)

    # 1) 标准加密→解密
    ct_std = encrypt(pt, rk, nr_test)
    pt2 = decrypt(ct_std, rk, nr_test)
    assert np.sum(pt != pt2) == 0, "标准加解密失败!"
    print("✓ 标准加解密验证通过")

    # 2) MC+InvMC vs 标准加密: 对比差分
    pt1 = np.frombuffer(urandom(16 * n_test), dtype=np.uint8).reshape(-1, 16)
    pt0 = pt1.copy()
    pt0[:, 0] ^= 0x80

    rk2 = expand_key(np.frombuffer(urandom(16 * n_test), dtype=np.uint8).reshape(-1, 16), nr_test)
    ct0_std = encrypt(pt0, rk2, nr_test, final_mc=False)
    ct1_std = encrypt(pt1, rk2, nr_test, final_mc=False)

    ct0_invmc = encrypt_with_invmc(pt0, rk2, nr_test)
    ct1_invmc = encrypt_with_invmc(pt1, rk2, nr_test)

    diff_std = ct0_std ^ ct1_std
    diff_invmc = ct0_invmc ^ ct1_invmc

    assert np.array_equal(diff_std, diff_invmc), "差分不一致!"
    print("✓ 差分 (c0⊕c1) 完全一致")

    # 3) 绝对值: InvMC(k3) 分布验证
    #    状态1: ct_std = SR(SB(x)) ⊕ k3
    #    状态2: ct_invmc = SR(SB(x)) ⊕ InvMC(k3)
    #    k3 随机 → InvMC(k3) 也是随机 16 字节 → 对区分器而言分布相同
    print(f"  标准 ct[0] 方差: {ct0_std[:, 0].var():.1f}")
    print(f"  InvMC ct[0] 方差: {ct0_invmc[:, 0].var():.1f}")
    print("✓ 所有验证通过")
